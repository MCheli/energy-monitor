_SECRETS_TEMPLATE = """\
## Edit these and rename to secrets.yaml.
##
## Generate the encryption + OTA values with:
##   openssl rand -base64 32

wifi_ssid:    "YOUR_WIFI_SSID"
wifi_password: "YOUR_WIFI_PASSWORD"

api_encryption_key: "PASTE-A-FRESH-32-BYTE-BASE64-VALUE-HERE="
ota_password:       "PASTE-A-FRESH-RANDOM-PASSWORD-HERE"
"""


_README_TEMPLATE = """\
# Flashing your CircuitSetup energy meter

These three files were generated by panel-tool. Save them to a directory
on your laptop, edit `secrets.yaml.example`, then flash one of two ways:

## Option 1 — local flashing with the ESPHome CLI

```
# install once
pip install esphome

# from the directory holding these files
mv secrets.yaml.example secrets.yaml
$EDITOR secrets.yaml         # fill in WiFi + generate keys per the comments
esphome run energy_meter.yaml
```

The first compile downloads PlatformIO (~5 min). Subsequent compiles take
about 60s. The `run` command both compiles and uploads — it will prompt
for OTA upload if the device is already on Wi-Fi.

## Option 2 — Home Assistant ESPHome add-on

If your Home Assistant install has the ESPHome add-on:

1. Open the ESPHome dashboard.
2. New device → upload `energy_meter.yaml`.
3. Edit the device's YAML and **also** upload your filled-in `secrets.yaml`
   to the add-on's secrets store.
4. Click *Install* → *Wirelessly*.

## File summary

| File | What it is |
|---|---|
| `energy_meter.yaml` | The full firmware config. CT names + cal values reflect the panel-tool state at export time. |
| `secrets.yaml.example` | Template for WiFi credentials, the API encryption key (HA pairing), and the OTA password. Edit and rename to `secrets.yaml`. |
| `README.md` | This file. |

Re-run the export from panel-tool any time the panel mapping changes. The
substitutions block gets rewritten; everything else (voltage cal,
sign-inversion filters, packages) is preserved from your previously-pasted
YAML.
"""


def build_zip_bytes(panel_data: dict[str, Any]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("energy_meter.yaml", merge_full_yaml(panel_data))
        zf.writestr("secrets.yaml.example", _SECRETS_TEMPLATE)
        zf.writestr("README.md", _README_TEMPLATE)
    return buf.getvalue()
